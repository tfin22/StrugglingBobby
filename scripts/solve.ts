// Find and record a route through each zone: npx vite-node scripts/solve.ts [zone...]
// Prints each screen as it is solved, and writes src/content/routes/data.ts.
import { writeFileSync, readFileSync } from 'node:fs';
import { newWorld, step } from '../src/game/world';
import { solveScreen, setGWeight } from '../src/game/solver';
import { encodeRoute, decodeRoute } from '../src/content/routes';
import { ROUTES } from '../src/content/routes/data';
import { ZONES } from '../src/content/zones';
import { botFor, runBot } from '../src/game/bots';

const args = process.argv.slice(2).map(Number).filter((n) => !isNaN(n));
const zones = args.length ? args : [0, 1, 2, 3];
const seed = 1938;
const routes = [...ROUTES];
for (const z of zones) {
  let w = newWorld({ zone: z, seed });
  const all: number[] = [];
  let ok = true;
  const t0 = Date.now();
  while (w.state !== 'zoneDone') {
    const from = w.screen;
    const def = ZONES[z].screens.find((s) => s.id === from)!;
    const bot = botFor(def.boss);
    let r = bot ? { ...runBot(w, bot, (x, i) => step(x, i)), nodes: 0 } : solveScreen(w, Number(process.env.NODES ?? 3000));
    if (bot && !r.ok) console.log(`  bot failed: ${r.world.deathCause} at frame ${r.inputs.length}, boss hp ${r.world.ents.find((e) => e.k === 'boss')?.hp}`);
    // Retry with a more patient search (waiting for pies, timing traps)
    for (const gw of [1.2, 3]) { if (r.ok || bot) break; setGWeight(gw); r = solveScreen(w, Number(process.env.NODES ?? 8000)); }
    setGWeight(0.4);
    if (!r.ok) { console.log(`zone ${z + 1}: STUCK on ${from} (${ZONES[z].screens.find((s) => s.id === from)?.name}) after ${r.nodes} nodes`); ok = false; break; }
    all.push(...r.inputs);
    w = r.world;
    console.log(`  ${from} -> ${w.state === 'zoneDone' ? 'DONE' : w.screen}  ${r.inputs.length}f ${r.nodes}n  pies ${w.pies} balls ${w.balls}`);
  }
  if (!ok) continue;
  // verify by replay
  const v = newWorld({ zone: z, seed });
  for (const f of all) { step(v, f); v.events.length = 0; }
  console.log(`zone ${z + 1}: ${(all.length / 50).toFixed(0)}s, replay ${v.state} deaths ${v.stats.deaths} (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  if (v.state !== 'zoneDone') { console.log('REPLAY MISMATCH'); continue; }
  const i = routes.findIndex((r) => r.zone === z);
  const rec = { zone: z, seed, route: encodeRoute(all) };
  if (i >= 0) routes[i] = rec; else routes.push(rec);
}
routes.sort((a, b) => a.zone - b.zone);
writeFileSync('src/content/routes/data.ts', `// Generated by scripts/solve.ts. Do not edit by hand.\nimport type { Route } from './index';\nexport const ROUTES: Route[] = ${JSON.stringify(routes, null, 1)};\n`);
void readFileSync; void decodeRoute;
